/**
 * Palettes: building roles → weighted materials (ids from materials.ts). One material per
 * role is chosen per building (seeded, weight = probability); texture variation inside a wall
 * comes from the material's weathering list and the roof blend of the roof engine, not from
 * mixing unrelated blocks ("palette chaos"). Roles are drawn independently, so wall, upper wall
 * and infill only list alternatives that work with every other choice.
 *
 * Sources: research_notes/Bauqualitaet 2026-10/07 (32 palettes after our roles, critique of the
 * old 19) and the style bibles 08–13 (section "(c) Paletten"), translated to this one-material-
 * per-role model. Checked by the palette lints (lints.ts) in ΔE00 of the measured texture colours
 * (textureStats.ts): wall ↔ frame ≥ 15, roof ≠ wall, the frame does not vanish in the roof, the
 * roof trim is a wooden or roof-family board, braces match the posts, calm glass, 3–5 families.
 * Pale oak (1.21.4+) appears only in roles the generator builds per version (frame, beam,
 * shutter, door, accent); 1.21.1 gets the stand-in from the registry (quartz pillar, iron
 * trapdoor, birch door).
 */

export const ROLES = [
  'plinth', // Sockel
  'wall', // Hauptwand (Erdgeschoss)
  'upperWall', // Wand der Obergeschosse (z. B. Holz über Stein-EG)
  'infill', // Fachwerkfüllung
  'frame', // Pfosten, Ständer, Fensterrahmen-Stämme (Holz-Outline)
  'beam', // liegende Balken an Geschosslinien
  'roof', // Dachfläche (Treppenfamilie)
  'roofTrim', // Ortgangbrett (äußerste Giebelspalte) im Kontrast
  'ridge', // First
  'soffit', // Untersicht (Kopfüber-Treppen)
  'window', // Glas
  'shutter', // Fensterläden (Falltüren)
  'door', // Tür (Holz- oder Metallfamilie)
  'floor', // Geschossdecken
  'path', // Weg vor der Tür
  'chimney', // Schornstein
  'accent', // ≤ 10 % Akzent
] as const;

export type Role = (typeof ROLES)[number];

export type Weighted = readonly [material: string, weight: number];

export interface Palette {
  id: string;
  label: string;
  roles: Readonly<Record<Role, readonly Weighted[]>>;
}

const one = (m: string): Weighted[] => [[m, 1]];

